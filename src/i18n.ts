const DICTS: Record<Lang, Dict> = { ru, de, en };
const LOCALES: Record<Lang, string> = { ru: 'ru-RU', de: 'de-DE', en: 'en-GB' };

export const LANG_NAMES: Record<Lang, string> = { ru: 'Русский', de: 'Deutsch', en: 'English' };

export type T = ((key: TKey, vars?: Record<string, string | number>) => string) & {
  lang: Lang;
  locale: string;
  date(date: string, opts: Intl.DateTimeFormatOptions): string;
  relativeDays(days: number): string;
};

const cache = new Map<Lang, T>();

export function translator(lang: Lang): T {
  const hit = cache.get(lang);
  if (hit) return hit;
  const dict = DICTS[lang] ?? ru;
  const locale = LOCALES[lang];
  const fn = ((key, vars) => {
    let s: string = dict[key] ?? ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }) as T;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
  fn.lang = lang;
  fn.locale = locale;
  fn.date = (date, opts) => new Intl.DateTimeFormat(locale, { ...opts, timeZone: 'UTC' }).format(toDisplayDate(date));
  fn.relativeDays = (days) => rtf.format(days, 'day');
  cache.set(lang, fn);
  return fn;
}

export function useT(): T {
  return translator(useStore(settingsStore).lang);
}
